// Packs the built game (dist/) into a module the Worker serves directly,
// so deploying needs only one upload.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('../dist/', import.meta.url).pathname;
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.json': 'application/json' };
const files = {};
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    const ext = f.slice(f.lastIndexOf('.'));
    if (!types[ext]) continue;
    files['/' + relative(root, p)] = { type: types[ext], body: readFileSync(p, 'utf8') };
  }
};
walk(root);
writeFileSync(new URL('../src/server/site.gen.ts', import.meta.url), `// Generated by scripts/embed.mjs — do not edit.\nexport const SITE: Record<string, { type: string; body: string }> = ${JSON.stringify(files)};\n`);
console.log('embedded', Object.keys(files).join(', '));
